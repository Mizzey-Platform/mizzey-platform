"""Turn the design tokens into the theme's token layer (spec 066, slice 1).

`design/tokens/tokens.json` (W3C Design Tokens format) is the one source of every colour, gradient, size, space,
radius, shadow, font, motion, layout and control value. This tool writes, from it:

- `<theme>/assets/css/tokens.css`: one `--mizzey-*` custom property for every token (a role points at its palette
  value with `var()`); a typography token also gets one property per part (`-font-size`, `-line-height`, ...) and
  a `font` shorthand; the type roles (`--mizzey-type-<role>-*`), Latin by default and Arabic on `:lang(ar)` where
  an Arabic role exists; and the reduced-motion form, where every duration takes `motion.duration.reduced` except
  those marked `keepWhenReduced` (fades of 120 ms or less stay, C1-System 11);
- the generated part of `<theme>/theme.json` `settings`: the palette (less any colour marked
  `$extensions.mizzey.editorPalette: false`), the gradients, the font families with their
  faces (from `<theme>/assets/fonts/fonts.json`, which `tools/theme_fonts.py` writes), the font sizes, the spacing
  scale, the radius sizes, the shadow presets, and the layout widths. Every other key is kept as it is.

A typography token may carry `$extensions.mizzey.fluid` as `{"fontSize": [at 390, at 1440], "lineHeight": [...]}`
and a dimension token as `[at 390, at 1440]`, in rem: each becomes a `clamp()` that grows linearly between the two
widths and holds outside them (FOUNDATIONS A.5).

    python tools/theme_tokens.py [--check] [--tokens PATH] [--theme DIR]

`--check` writes nothing and exits 1 when the checked-in output is stale.
"""

from __future__ import annotations

import argparse
import copy
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "design" / "tokens" / "tokens.json"
THEME = ROOT / "mizzey-theme"

FLUID_MIN_VIEWPORT = 390
FLUID_MAX_VIEWPORT = 1440
ROOT_PX = 16
REF = re.compile(r"^\{([a-z0-9.-]+)\}$")
GENERIC_FAMILIES = {"serif", "sans-serif", "monospace", "cursive", "fantasy", "system-ui", "-apple-system",
                    "ui-sans-serif", "ui-serif", "ui-monospace", "math", "emoji"}
TYPE_PARTS = (("fontFamily", "font-family"), ("fontWeight", "font-weight"), ("fontSize", "font-size"),
              ("lineHeight", "line-height"), ("letterSpacing", "letter-spacing"),
              ("fontFeatureSettings", "font-feature-settings"), ("textDecoration", "text-decoration"))
HEADER = ("/* Generated by tools/theme_tokens.py from design/tokens/tokens.json. Do not edit: change the token and\n"
          "   run the tool again. */\n")


def paths(theme_dir: Path) -> dict[str, Path]:
    return {"theme_json": theme_dir / "theme.json", "css": theme_dir / "assets" / "css" / "tokens.css",
            "fonts": theme_dir / "assets" / "fonts" / "fonts.json"}


# Reading ---------------------------------------------------------------------------------------------------------

def load_tokens(path: Path = TOKENS) -> dict[str, dict]:
    """Every token in the file, keyed by its dotted path, in file order."""
    found: dict[str, dict] = {}

    def walk(node: dict, trail: list[str]) -> None:
        if "$value" in node:
            found[".".join(trail)] = node
            return
        for key, child in node.items():
            if not key.startswith("$") and isinstance(child, dict):
                walk(child, trail + [key])

    walk(json.loads(path.read_text(encoding="utf-8")), [])
    return found


def load_fonts_manifest(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def css_name(path: str) -> str:
    return "--mizzey-" + slug(path)


def slug(path: str) -> str:
    return path.replace(".", "-")


def mizzey(token: dict) -> dict:
    return token.get("$extensions", {}).get("mizzey", {})


def resolve(value, tokens: dict[str, dict]):
    """The literal value behind a reference, followed to the end."""
    seen = set()
    while isinstance(value, str) and REF.match(value):
        target = REF.match(value).group(1)
        if target in seen or target not in tokens:
            raise ValueError(f"unresolvable token reference {value}")
        seen.add(target)
        value = tokens[target]["$value"]
    return value


# Values ----------------------------------------------------------------------------------------------------------

def family_stack(families: list[str]) -> str:
    return ", ".join(f if f in GENERIC_FAMILIES else f'"{f}"' for f in families)


def with_fallbacks(families: list[str], manifest: dict) -> list[str]:
    """The family stack with the metric-matched fallback faces of `fonts.json` right after the web font."""
    stack = list(families)
    stack[1:1] = manifest.get("fallbacks", {}).get(stack[0], [])
    return stack


def fluid_clamp(min_rem: str, max_rem: str, lo: int = FLUID_MIN_VIEWPORT, hi: int = FLUID_MAX_VIEWPORT) -> str:
    """A length that grows linearly from `min_rem` at `lo` px wide to `max_rem` at `hi` px, clamped outside."""
    a, b = float(min_rem.removesuffix("rem")), float(max_rem.removesuffix("rem"))
    slope = (b - a) * ROOT_PX / (hi - lo)
    intercept = a - slope * lo / ROOT_PX
    return f"clamp({_num(a)}rem, {_num(intercept)}rem + {_num(slope * 100)}vw, {_num(b)}rem)"


def _num(value: float, places: int = 4) -> str:
    text = f"{value:.{places}f}".rstrip("0").rstrip(".")
    return text if text not in ("-0", "") else "0"


def ref_or(value, tokens: dict[str, dict] | None = None) -> str | None:
    if isinstance(value, str) and REF.match(value):
        return f"var({css_name(REF.match(value).group(1))})"
    return None


def shadow_layer(layer: dict) -> str:
    colour = ref_or(layer["color"]) or layer["color"]
    return f"{layer['offsetX']} {layer['offsetY']} {layer['blur']} {layer['spread']} {colour}"


def css_value(token: dict, literal: bool = False, tokens: dict[str, dict] | None = None) -> str:
    """One CSS value for a token; a reference becomes `var()`, or its literal value when `literal` is set."""
    kind, value = token["$type"], token["$value"]
    if literal and tokens is not None:
        if isinstance(value, str) and REF.match(value):
            return css_value(tokens[REF.match(value).group(1)], literal, tokens)
    reference = ref_or(value)
    if reference:
        return reference
    fluid = mizzey(token).get("fluid")
    if kind == "dimension" and isinstance(fluid, list):
        return fluid_clamp(*fluid)
    if kind == "fontFamily":
        return family_stack(value)
    if kind == "cubicBezier":
        return "cubic-bezier(" + ", ".join(_num(float(v)) for v in value) + ")"
    if kind == "shadow":
        layers = value if isinstance(value, list) else [value]
        if literal and tokens is not None:
            layers = [{**layer, "color": resolve(layer["color"], tokens)} for layer in layers]
        return ", ".join(shadow_layer(layer) for layer in layers)
    if kind == "gradient":
        angle = mizzey(token).get("angle", "180deg")
        stops = []
        for stop in value:
            colour = resolve(stop["color"], tokens) if literal and tokens is not None else (
                ref_or(stop["color"]) or stop["color"])
            stops.append(f"{colour} {_num(stop['position'] * 100, 2)}%")
        return f"linear-gradient({angle}, " + ", ".join(stops) + ")"
    return str(value)


def typography_lines(path: str, token: dict) -> list[str]:
    name = css_name(path)
    fluid = mizzey(token).get("fluid") or {}
    lines = []
    for key, prop in TYPE_PARTS:
        if key not in token["$value"]:
            continue
        raw = token["$value"][key]
        if key in fluid:
            value = fluid_clamp(*fluid[key])
        else:
            value = ref_or(raw) or str(raw)
        lines.append(f"{name}-{prop}: {value};")
    lines.append(f"{name}: var({name}-font-weight) var({name}-font-size)/var({name}-line-height) "
                 f"var({name}-font-family);")
    return lines


def roles(tokens: dict[str, dict], script: str) -> list[str]:
    return [p.split(".")[2] for p in tokens if p.startswith(f"type.{script}.")]


def role_lines(tokens: dict[str, dict], script: str) -> list[str]:
    lines = []
    for role in roles(tokens, script):
        token = tokens[f"type.{script}.{role}"]
        source = css_name(f"type.{script}.{role}")
        for key, prop in TYPE_PARTS:
            if key in token["$value"]:
                lines.append(f"--mizzey-type-{role}-{prop}: var({source}-{prop});")
        lines.append(f"--mizzey-type-{role}: var({source});")
    return lines


# Rendering -------------------------------------------------------------------------------------------------------

def render_css(tokens: dict[str, dict], manifest: dict | None = None) -> str:
    root = []
    for path, token in tokens.items():
        if token["$type"] == "fontFamily":
            root.append(f"{css_name(path)}: {family_stack(with_fallbacks(token['$value'], manifest or {}))};")
        elif token["$type"] == "typography":
            root.extend(typography_lines(path, token))
        else:
            root.append(f"{css_name(path)}: {css_value(token)};")
    root.extend(role_lines(tokens, "latin"))
    out = [HEADER, ":root {", *("\t" + line for line in root), "}", ""]
    arabic = role_lines(tokens, "arabic")
    if arabic:
        out += [":root:lang(ar) {", *("\t" + line for line in arabic), "}", ""]
    for role in roles(tokens, "latin"):
        parts = tokens[f"type.latin.{role}"]["$value"]
        rule = [f"font: var(--mizzey-type-{role});"]
        for key, prop in TYPE_PARTS[4:]:
            if key in parts:
                rule.append(f"{prop}: var(--mizzey-type-{role}-{prop});")
        out += [f".mizzey-type--{role} {{", *("\t" + line for line in rule), "}", ""]
    reduced = [p for p, t in tokens.items() if t["$type"] == "duration" and p != "motion.duration.reduced"
               and not mizzey(t).get("keepWhenReduced")]
    if "motion.duration.reduced" in tokens and reduced:
        out += ["@media (prefers-reduced-motion: reduce) {", "\t:root {",
                *(f"\t\t{css_name(p)}: var(--mizzey-motion-duration-reduced);" for p in reduced), "\t}", "}", ""]
    return "\n".join(out)


def label(path: str) -> str:
    return " ".join(part.replace("-", " ") for part in path.split(".")).title()


def font_faces(manifest: dict, family: str) -> list[dict]:
    keep = ("fontFamily", "fontWeight", "fontStyle", "fontDisplay", "src", "unicodeRange")
    return [{k: v for k, v in face.items() if k in keep}
            for face in manifest.get("faces", []) if face["fontFamily"] == family]


def render_theme_json(theme: dict, tokens: dict[str, dict], manifest: dict) -> dict:
    out = copy.deepcopy(theme)
    settings = out.setdefault("settings", {})
    of = lambda kind: [(p, t) for p, t in tokens.items() if t["$type"] == kind]  # noqa: E731

    color = settings.setdefault("color", {})
    color["defaultPalette"] = False
    color["defaultGradients"] = False
    # A colour marked `editorPalette: false` stays a token for the theme's own styles but is not offered in the
    # editor's colour pickers: Persimmon is a fill in fixed places only, never text (D-35).
    color["palette"] = [{"slug": slug(p), "name": label(p.split(".", 1)[1]), "color": resolve(t["$value"], tokens)}
                        for p, t in of("color") if mizzey(t).get("editorPalette", True) is not False]
    color["gradients"] = [{"slug": slug(p), "name": label(p.split(".", 1)[1]),
                           "gradient": css_value(t, literal=True, tokens=tokens)} for p, t in of("gradient")]

    typography = settings.setdefault("typography", {})
    typography["defaultFontSizes"] = False
    typography["fluid"] = False
    families = []
    for path, token in of("fontFamily"):
        stack = with_fallbacks(token["$value"], manifest)
        entry = {"slug": slug(path), "name": label(path.split(".", 2)[2]), "fontFamily": family_stack(stack)}
        faces = font_faces(manifest, stack[0])
        if faces and path != "font.family.numeric":
            entry["fontFace"] = faces
        families.append(entry)
    typography["fontFamilies"] = families
    typography["fontSizes"] = [{"slug": slug(f"type.{role}"), "name": label(role),
                                "size": f"var(--mizzey-type-{role}-font-size)"} for role in roles(tokens, "latin")]

    spacing = settings.setdefault("spacing", {})
    spacing["defaultSpacingSizes"] = False
    spacing["spacingSizes"] = [{"slug": slug(p), "name": p.split(".", 1)[1], "size": css_value(t)}
                               for p, t in tokens.items() if p.startswith("space.")]

    settings.setdefault("border", {})["radiusSizes"] = [
        {"slug": slug(p), "name": label(p.split(".", 1)[1]), "size": t["$value"]}
        for p, t in tokens.items() if p.startswith("radius.")]

    shadow = settings.setdefault("shadow", {})
    shadow["defaultPresets"] = False
    shadow["presets"] = [{"slug": slug(p), "name": label(p), "shadow": css_value(t, literal=True, tokens=tokens)}
                         for p, t in of("shadow")]

    layout = settings.setdefault("layout", {})
    if "layout.reading-width" in tokens:
        layout["contentSize"] = tokens["layout.reading-width"]["$value"]
    if "layout.content-width" in tokens:
        layout["wideSize"] = tokens["layout.content-width"]["$value"]
    return out


def dump_theme_json(theme: dict) -> str:
    return json.dumps(theme, indent="\t", ensure_ascii=False) + "\n"


def generate(tokens_path: Path, theme_dir: Path) -> dict[Path, str]:
    """The text of every file the tool writes, keyed by path."""
    files = paths(theme_dir)
    tokens = load_tokens(tokens_path)
    fonts = load_fonts_manifest(files["fonts"])
    theme = json.loads(files["theme_json"].read_text(encoding="utf-8")) if files["theme_json"].exists() else {}
    return {files["css"]: render_css(tokens, fonts),
            files["theme_json"]: dump_theme_json(render_theme_json(theme, tokens, fonts))}


# Command ---------------------------------------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when the output is stale")
    parser.add_argument("--tokens", type=Path, default=TOKENS)
    parser.add_argument("--theme", type=Path, default=THEME)
    args = parser.parse_args(argv)

    output = generate(args.tokens, args.theme)
    stale = [p for p, text in output.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"stale: {path}")
        return 1 if stale else 0
    for path, text in output.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(load_tokens(args.tokens))} tokens; {len(stale)} file(s) changed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
